class Mentor:
    """
    Родительский (базовый) класс для всех ролей преподавателей.

    Содержит общую информацию, характерную для всех наставников:
    имя, фамилию и список курсов, к которым они прикреплены.
    Сам по себе не реализует специфичных методов оценки.

    Атрибуты:
        name (str): Имя наставника.
        surname (str): Фамилия наставника.
        courses_attached (list): Список названий курсов, которые ведет/проверяет наставник.
    """

    def __init__(self, name: str, surname: str):
        """
        Инициализирует нового наставника.

        Args:
            name (str): Имя наставника.
            surname (str): Фамилия наставника.
        """
        self.name = name
        self.surname = surname
        self.courses_attached = []